        check(c.cache.vaultName===database&&database!==app.vault.getName(),'Cache must be independently owned');
        c.index.scheduleOrphanCleanup=/** This isolated cache is purged on exit; no later native cleanup timer is needed. */ ()=>{};
        check(await c.index.rebuild(),'Actual native full graph');
        check(await c.index.sourceAcquisition.reconcile(),'Prime actual neutral sources outside measured hydration');
        check(await c.index.persistIndexedDbSnapshot(c.index.snapshotPersistGeneration),'Actual current-schema snapshot writer');
